EDGES = [e for e in EDGES if e.src in COMPANY_BY_TICKER and e.dst in COMPANY_BY_TICKER]


def neighbors(ticker: str) -> list[Edge]:
    """All edges touching `ticker`, either direction."""
    return [e for e in EDGES if e.src == ticker or e.dst == ticker]


def adjacency() -> dict[str, list[tuple[str, Edge]]]:
    """ticker -> [(other_ticker, edge), ...] for graph algorithms."""
    adj: dict[str, list[tuple[str, Edge]]] = {t: [] for t in TICKERS}
    for e in EDGES:
        adj[e.src].append((e.dst, e))
        adj[e.dst].append((e.src, e))
    return adj
