"""The starter universe: ~100 real, mostly-interconnected companies and the
real-world relationships between them (supplier / customer / competitor /
partner). This is the graph the whole product is built around.

Edge types:
    supplier   A supplies B (A -> B means "A supplies to B")
    customer   A is a major customer/buyer of B's output (inverse of supplier,
               kept separate so the direction of $ flow is explicit)
    competitor A and B compete directly for the same customers
    partner    A and B have a strategic partnership / alliance / joint venture

Weight (0-1) is a rough "how much this relationship matters to both
companies' stock price" judgment call, used to scale graph spillover.
"""
